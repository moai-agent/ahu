//! The committed project context lock.
//!
//! The lock fingerprints the repository context ahu recognizes. Launches require
//! both the lock and every recognized context input to be committed and clean.
//! This cannot lock harness built-ins, managed policy, or other opaque sources.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::bail;
use crate::git::{self, Repo};
use crate::private_io::Durability;
use crate::snapshot::{ConfigSnapshot, SnapshotEntry};
use crate::util::{Error, Result, digest_bytes};

pub const LOCK_PATH: &str = ".agents/ahu/lock.md";
pub const LEGACY_LOCK_PATH: &str = "ahu.lock";
const LOCK_SCHEMA_VERSION: u32 = 1;

/// User-local inputs are locked in owner-only host state so they affect launch
/// admission without adding user-specific fingerprints to shared `.agents/ahu/lock.md`.
fn private_paths(repo: &Repo) -> Result<Vec<String>> {
    let mut paths = BTreeSet::new();
    for descriptor in crate::harness_runtime::discover_context(repo)? {
        for path in parse_private_paths(&serde_json::to_value(descriptor.private_context_paths)?)? {
            paths.insert(path);
        }
    }
    Ok(paths.into_iter().collect())
}
fn parse_private_paths(value: &serde_json::Value) -> Result<Vec<String>> {
    let paths: Vec<String> = serde_json::from_value(value.clone())
        .map_err(|_| Error::new("invalid private context paths"))?;
    if paths.len() > 64
        || paths.iter().any(|path| {
            path.len() > 4096 || !crate::plugin_binding::plain_relative(path.trim_end_matches('/'))
        })
    {
        return Err(Error::new("invalid private context paths"));
    }
    Ok(paths)
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub(crate) struct LockFile {
    schema_version: u32,
    digest: String,
    #[serde(deserialize_with = "strict_entries")]
    entries: Vec<SnapshotEntry>,
    skipped_directories: Vec<String>,
    unscanned_config: Vec<String>,
    symlinks: Vec<String>,
}

// Lock schemas are strict without tightening the historical task-record
// SnapshotEntry reader, which must keep its existing compatibility behavior.
fn strict_entries<'de, D: serde::Deserializer<'de>>(
    deserializer: D,
) -> std::result::Result<Vec<SnapshotEntry>, D::Error> {
    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct Entry {
        path: String,
        digest: String,
        bytes: u64,
        #[serde(default)]
        executable: bool,
    }
    Vec::<Entry>::deserialize(deserializer).map(|entries| {
        entries
            .into_iter()
            .map(|e| SnapshotEntry {
                path: e.path,
                digest: e.digest,
                bytes: e.bytes,
                executable: e.executable,
            })
            .collect()
    })
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Status {
    pub current: bool,
    pub detail: String,
}

impl LockFile {
    pub(crate) fn from_snapshot(snapshot: &ConfigSnapshot) -> Self {
        let snapshot = snapshot.clone();
        Self {
            schema_version: LOCK_SCHEMA_VERSION,
            digest: context_digest(&snapshot),
            entries: snapshot.entries,
            skipped_directories: snapshot.skipped_directories,
            unscanned_config: snapshot.unscanned_config,
            symlinks: snapshot.symlinks,
        }
    }

    pub(crate) fn matches_snapshot(&self, snapshot: &ConfigSnapshot) -> bool {
        let mut current = Self::from_snapshot(snapshot);
        current
            .skipped_directories
            .clone_from(&self.skipped_directories);
        *self == current
    }
    pub(crate) fn parse(path: &Path) -> Result<Self> {
        let bytes = crate::okf::read(path)?;
        Self::decode(
            &bytes,
            path.file_name()
                .is_some_and(|name| name == LEGACY_LOCK_PATH),
        )
    }
    pub(crate) fn decode(bytes: &[u8], legacy: bool) -> Result<Self> {
        let text =
            std::str::from_utf8(bytes).map_err(|_| Error::new("context lock is not UTF-8"))?;
        let lock: Self = if legacy {
            toml::from_str(text).map_err(|_| Error::new("context lock is not valid TOML"))?
        } else {
            crate::okf::Document::parse(text, "ahu:lock")?.settings()?
        };
        if lock.schema_version != LOCK_SCHEMA_VERSION {
            bail!("unsupported context lock schema_version");
        }
        Ok(lock)
    }
    pub(crate) fn render(&self, previous: Option<&str>) -> Result<String> {
        let mut document = match previous {
            Some(text) => crate::okf::Document::parse(text, "ahu:lock")?,
            None => crate::okf::Document::new(
                "ahu:lock",
                self,
                "\n# Shared context pins\n\nGenerated by ahu. These pins do not prove harness loading.\n",
            )?,
        };
        document.set_settings(self)?;
        document.render()
    }
}

fn context_digest(snapshot: &ConfigSnapshot) -> String {
    lock_digest(
        &snapshot.entries,
        &snapshot.unscanned_config,
        &snapshot.symlinks,
    )
}

fn lock_digest(
    entries: &[SnapshotEntry],
    unscanned_config: &[String],
    symlinks: &[String],
) -> String {
    let mut entries = entries.to_vec();
    entries.sort_by(|left, right| left.path.cmp(&right.path));
    let canonical = serde_json::json!({
        "entries": entries,
        "unscanned_config": unscanned_config,
        "symlinks": symlinks,
    });
    digest_bytes(canonical.to_string().as_bytes())
}

fn is_local_context_path(path: &str, paths: &[String]) -> bool {
    path.starts_with("native:")
        || paths.iter().any(|local| {
            path == local.trim_end_matches('/') || (local.ends_with('/') && path.starts_with(local))
        })
}

fn shared_snapshot(snapshot: &ConfigSnapshot, private: &[String]) -> ConfigSnapshot {
    let mut shared = snapshot.clone();
    shared
        .entries
        .retain(|entry| !is_local_context_path(&entry.path, private));
    shared
        .unscanned_config
        .retain(|path| !is_local_context_path(path, private));
    shared
        .symlinks
        .retain(|path| !is_local_context_path(path, private));
    shared
}

fn local_fingerprints(
    repo: &Repo,
    snapshot: &ConfigSnapshot,
    private: &[String],
) -> Result<BTreeMap<String, String>> {
    let mut fingerprints: BTreeMap<String, String> = snapshot
        .entries
        .iter()
        .filter(|entry| is_local_context_path(&entry.path, private))
        .map(|entry| (entry.path.clone(), entry.digest.clone()))
        .collect();
    for descriptor in crate::harness_runtime::discover(repo)? {
        if descriptor
            .operations
            .contains(&crate::harness_runtime::Operation::NativeSources)
        {
            for (key, digest) in crate::native_mcp::fingerprints(repo, &descriptor.id)? {
                if fingerprints.insert(key, digest).is_some() {
                    return Err(Error::new("duplicate private native fingerprint"));
                }
            }
        }
    }
    Ok(fingerprints)
}

pub fn refresh(repo: &Repo, snapshot: &ConfigSnapshot) -> Result<PathBuf> {
    refresh_with_state_home(repo, snapshot, None)
}

/// Refresh project context as part of explicit setup. A first setup establishes
/// local acceptance, while rerunning setup never silently accepts later drift.
pub fn refresh_for_setup(repo: &Repo, snapshot: &ConfigSnapshot) -> Result<PathBuf> {
    let private = private_paths(repo)?;
    reject_local_symlinks(snapshot, &private)?;
    let path = write_shared_lock(repo, snapshot)?;
    crate::private_context_lock::initialize_if_missing(
        repo,
        &local_fingerprints(repo, snapshot, &private)?,
    )?;
    Ok(path)
}

#[doc(hidden)]
pub fn refresh_with_state_home(
    repo: &Repo,
    snapshot: &ConfigSnapshot,
    state_home: Option<&Path>,
) -> Result<PathBuf> {
    let private = private_paths(repo)?;
    reject_local_symlinks(snapshot, &private)?;
    let path = write_shared_lock(repo, snapshot)?;
    let fingerprints = local_fingerprints(repo, snapshot, &private)?;
    // Explicit acceptance includes deletion of the last private input. The
    // private store avoids creating state when there is nothing to accept.
    crate::private_context_lock::accept(repo, &fingerprints, state_home)?;
    Ok(path)
}

fn write_shared_lock(repo: &Repo, snapshot: &ConfigSnapshot) -> Result<PathBuf> {
    crate::migration::ensure_idle(&repo.root)?;
    if crate::util::resolve_existing_within(&repo.root, LEGACY_LOCK_PATH)?.is_some() {
        bail!(
            "legacy ahu.lock requires explicit `ahu migrate --preview` then `ahu migrate --apply`"
        );
    }
    let path = crate::util::resolve_within(&repo.root, LOCK_PATH, true)?;
    let previous = if path.exists() {
        let bytes = crate::okf::read(&path)?;
        LockFile::decode(&bytes, false)?;
        Some(String::from_utf8(bytes).map_err(|_| Error::new("lock is not UTF-8"))?)
    } else {
        None
    };
    let private = private_paths(repo)?;
    let lock = LockFile::from_snapshot(&shared_snapshot(snapshot, &private));
    let body = lock.render(previous.as_deref())?;
    crate::private_io::atomic_write(&path, body.as_bytes(), Durability::Durable)?;
    Ok(path)
}

/// Write only the shared lock for fixtures that intentionally contain an
/// unsafe local input, so they can assert that later launch admission refuses it.
#[doc(hidden)]
pub fn refresh_shared_only(repo: &Repo, snapshot: &ConfigSnapshot) -> Result<PathBuf> {
    write_shared_lock(repo, snapshot)
}

fn reject_local_symlinks(snapshot: &ConfigSnapshot, private: &[String]) -> Result<()> {
    if snapshot
        .symlinks
        .iter()
        .any(|path| is_local_context_path(path, private))
    {
        return Err(Error::new(
            "private local agent settings cannot be symlinks; replace the link with a regular file before accepting context",
        ));
    }
    Ok(())
}

/// Compare the lock to current inputs, then require all those inputs and the
/// lock itself to match committed HEAD. Call this before any candidate launch.
pub fn check(repo: &Repo, snapshot: &ConfigSnapshot) -> Result<Status> {
    check_with_state_home(repo, snapshot, None)
}

#[doc(hidden)]
pub fn check_with_state_home(
    repo: &Repo,
    snapshot: &ConfigSnapshot,
    state_home: Option<&Path>,
) -> Result<Status> {
    crate::migration::ensure_idle(&repo.root)?;
    let canonical = crate::util::resolve_existing_within(&repo.root, LOCK_PATH)?;
    let legacy = crate::util::resolve_existing_within(&repo.root, LEGACY_LOCK_PATH)?;
    if canonical.is_some() && legacy.is_some() {
        bail!("conflicting context lock formats; use explicit migration");
    }
    let Some(path) = canonical.or(legacy) else {
        return Ok(Status {
            current: false,
            detail: format!("{LOCK_PATH} is missing; run `ahu lock --update`, then commit it"),
        });
    };
    let lock_path = if path.ends_with(LEGACY_LOCK_PATH) {
        LEGACY_LOCK_PATH
    } else {
        LOCK_PATH
    };
    let lock = LockFile::parse(&path)?;

    let private = private_paths(repo)?;
    let current = LockFile::from_snapshot(&shared_snapshot(snapshot, &private));
    let mut problems = Vec::new();
    let obsolete_local_metadata = lock
        .entries
        .iter()
        .any(|entry| is_local_context_path(&entry.path, &private))
        || lock
            .unscanned_config
            .iter()
            .any(|path| is_local_context_path(path, &private))
        || lock
            .symlinks
            .iter()
            .any(|path| is_local_context_path(path, &private));
    if obsolete_local_metadata {
        problems.push("shared lock contains obsolete per-user metadata; refresh it".into());
    }
    let lock_entries: Vec<_> = lock
        .entries
        .iter()
        .filter(|entry| !is_local_context_path(&entry.path, &private))
        .cloned()
        .collect();
    let lock_unscanned: Vec<_> = lock
        .unscanned_config
        .iter()
        .filter(|path| !is_local_context_path(path, &private))
        .cloned()
        .collect();
    let lock_symlinks: Vec<_> = lock
        .symlinks
        .iter()
        .filter(|path| !is_local_context_path(path, &private))
        .cloned()
        .collect();
    let comparable_lock_digest = if obsolete_local_metadata {
        lock_digest(&lock_entries, &lock_unscanned, &lock_symlinks)
    } else {
        lock.digest.clone()
    };
    if comparable_lock_digest != current.digest {
        let before: BTreeMap<_, _> = lock_entries.iter().map(|item| (&item.path, item)).collect();
        let after: BTreeMap<_, _> = current
            .entries
            .iter()
            .map(|item| (&item.path, item))
            .collect();
        let paths: BTreeSet<_> = before.keys().chain(after.keys()).copied().collect();
        let mut changed = Vec::new();
        for path in paths {
            if before.get(path) != after.get(path) {
                changed.push(path.as_str());
            }
        }
        if !changed.is_empty() {
            problems.push(format!(
                "context differs from shared lock: {}",
                changed.join(", ")
            ));
        }
        if lock_unscanned != current.unscanned_config || lock_symlinks != current.symlinks {
            problems.push("context scan coverage changed".into());
        }
        if problems.is_empty() {
            problems.push("context digest differs from shared lock".into());
        }
    }

    let lock_tracked = is_tracked(&repo.root, lock_path)?;
    if !lock_tracked {
        problems.push(format!("{lock_path} is not tracked by Git"));
    } else if !is_clean_at_head(&repo.root, lock_path)? {
        problems.push(format!("{lock_path} has uncommitted changes"));
    }

    // Include removed inputs from the lock as well as current files; a deleted
    // context file still has to be committed with the new lock.
    let mut paths: BTreeSet<&str> = snapshot
        .entries
        .iter()
        .map(|entry| entry.path.as_str())
        .collect();
    paths.extend(lock.entries.iter().map(|entry| entry.path.as_str()));
    for path in paths {
        if is_local_context_path(path, &private) {
            continue;
        }
        if !is_tracked(&repo.root, path)? {
            problems.push(format!("{path} is not tracked by Git"));
        } else if !is_clean_at_head(&repo.root, path)? {
            problems.push(format!("{path} has uncommitted changes"));
        }
    }

    let shared = shared_snapshot(snapshot, &private);
    if !shared.symlinks.is_empty() {
        problems.push(format!(
            "context symlinks cannot be locked safely: {}",
            shared.symlinks.join(", ")
        ));
    }
    if !shared.unscanned_config.is_empty() {
        problems.push(format!(
            "configuration inside skipped scan paths is not lockable: {}",
            shared.unscanned_config.join(", ")
        ));
    }

    let has_local_symlink = snapshot
        .symlinks
        .iter()
        .any(|path| is_local_context_path(path, &private));
    if has_local_symlink
        || !crate::private_context_lock::is_current(
            repo,
            &local_fingerprints(repo, snapshot, &private)?,
            state_home,
        )?
    {
        problems.push("private local agent settings are new or changed for this user".into());
    }

    Ok(if problems.is_empty() {
        Status {
            current: true,
            detail: format!("{} matches committed context", LOCK_PATH),
        }
    } else {
        Status {
            current: false,
            detail: format!(
                "{}; run `ahu lock --update`, then review and commit .agents/ahu/lock.md if shared context changed",
                problems.join("; ")
            ),
        }
    })
}

fn is_tracked(root: &Path, path: &str) -> Result<bool> {
    let output = git::run(
        root,
        &[
            "--literal-pathspecs",
            "ls-files",
            "--error-unmatch",
            "--",
            path,
        ],
    )?;
    Ok(output.status.success())
}

fn is_clean_at_head(root: &Path, path: &str) -> Result<bool> {
    let output = git::run(
        root,
        &[
            "--literal-pathspecs",
            "diff",
            "--name-only",
            "HEAD",
            "--",
            path,
        ],
    )?;
    if output.status.success() {
        Ok(output.stdout.is_empty())
    } else {
        bail!(
            "cannot compare {path} with committed HEAD: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::git;
    use std::process::Command;

    fn git_cmd(dir: &Path, args: &[&str]) {
        let output = Command::new("git")
            .args(args)
            .current_dir(dir)
            .env("GIT_CONFIG_GLOBAL", "/dev/null")
            .env("GIT_CONFIG_SYSTEM", "/dev/null")
            .env("GIT_AUTHOR_NAME", "ahu tests")
            .env("GIT_AUTHOR_EMAIL", "tests@example.invalid")
            .env("GIT_COMMITTER_NAME", "ahu tests")
            .env("GIT_COMMITTER_EMAIL", "tests@example.invalid")
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

    #[test]
    fn lock_requires_update_commit_and_clean_context_before_it_passes() {
        let fixture = tempfile::tempdir().unwrap();
        git_cmd(fixture.path(), &["init", "-q", "-b", "main"]);
        git_cmd(fixture.path(), &["config", "user.name", "ahu tests"]);
        git_cmd(
            fixture.path(),
            &["config", "user.email", "tests@example.invalid"],
        );
        std::fs::create_dir_all(fixture.path().join(".agents/ahu")).unwrap();
        std::fs::write(
            fixture.path().join(".agents/ahu/config.toml"),
            "schema_version = 1\n",
        )
        .unwrap();
        let repo = git::discover(fixture.path()).unwrap();
        let snapshot = crate::snapshot::collect(fixture.path()).unwrap();
        refresh(&repo, &snapshot).unwrap();
        assert!(!check(&repo, &snapshot).unwrap().current);
        git_cmd(fixture.path(), &["add", "-A"]);
        git_cmd(fixture.path(), &["commit", "-q", "-m", "lock"]);
        let repo = git::discover(fixture.path()).unwrap();
        assert!(check(&repo, &snapshot).unwrap().current);

        std::fs::write(
            fixture.path().join(".agents/ahu/config.toml"),
            "schema_version = 2\n",
        )
        .unwrap();
        let changed = crate::snapshot::collect(fixture.path()).unwrap();
        let status = check(&repo, &changed).unwrap();
        assert!(!status.current);
        assert!(status.detail.contains("uncommitted changes"));

        refresh(&repo, &changed).unwrap();
        assert!(!check(&repo, &changed).unwrap().current);
    }

    #[test]
    fn declared_private_context_never_enters_shared_lock() {
        let private = parse_private_paths(&serde_json::json!([
            ".invented/local.json",
            ".invented/private/"
        ]))
        .unwrap();
        let snapshot = ConfigSnapshot {
            entries: vec![
                SnapshotEntry {
                    path: "AGENTS.md".into(),
                    digest: "a".repeat(64),
                    bytes: 3,
                    executable: false,
                },
                SnapshotEntry {
                    path: ".invented/local.json".into(),
                    digest: "b".repeat(64),
                    bytes: 4,
                    executable: false,
                },
                SnapshotEntry {
                    path: "native:invented:0".into(),
                    digest: "c".repeat(64),
                    bytes: 0,
                    executable: false,
                },
            ],
            skipped_directories: vec![],
            unscanned_config: vec![".invented/private/child".into()],
            symlinks: vec![".invented/local.json".into()],
        };
        let shared = shared_snapshot(&snapshot, &private);
        assert_eq!(shared.entries.len(), 1);
        assert!(shared.unscanned_config.is_empty());
        assert!(shared.symlinks.is_empty());
        assert!(reject_local_symlinks(&snapshot, &private).is_err());
        let rendered = LockFile::from_snapshot(&shared).render(None).unwrap();
        assert!(!rendered.contains("invented"));
        assert!(!rendered.contains(&"b".repeat(64)));
        assert!(parse_private_paths(&serde_json::json!(["../escape"])).is_err());
        assert!(parse_private_paths(&serde_json::json!(["/absolute"])).is_err());
    }

    #[test]
    fn a_missing_or_symlink_lock_is_not_accepted() {
        let fixture = tempfile::tempdir().unwrap();
        git_cmd(fixture.path(), &["init", "-q", "-b", "main"]);
        git_cmd(fixture.path(), &["config", "user.name", "ahu tests"]);
        git_cmd(
            fixture.path(),
            &["config", "user.email", "tests@example.invalid"],
        );
        std::fs::write(fixture.path().join("README.md"), "fixture\n").unwrap();
        git_cmd(fixture.path(), &["add", "README.md"]);
        git_cmd(fixture.path(), &["commit", "-q", "-m", "base"]);
        let repo = git::discover(fixture.path()).unwrap();
        assert!(!check(&repo, &ConfigSnapshot::default()).unwrap().current);
        #[cfg(unix)]
        {
            let external = fixture.path().join("external-lock");
            std::fs::write(&external, "schema_version = 1\n").unwrap();
            std::fs::create_dir_all(fixture.path().join(".agents/ahu")).unwrap();
            std::os::unix::fs::symlink(&external, fixture.path().join(LOCK_PATH)).unwrap();
            assert!(check(&repo, &ConfigSnapshot::default()).is_err());
        }
    }
}
